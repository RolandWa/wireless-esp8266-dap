#!/usr/bin/env python3
"""Generate main/vtarget_cal_boards.c (per-board VTarget calibration tables).

Reads the 101-point DMM sweeps written by tests/pwm_vtarget_dmm.py
(tests/test_results/vtarget_PCB-xx_measurements.csv, columns duty_count and
dmm_mv) and reduces each board's curve to at most --max-points points by
greedy refinement: start with the two end points and keep adding the measured
point that the current piecewise-linear curve misses by the most, until every
measured point is within --tol-mv.

The output is deterministic (no timestamps) so `--check` can verify in CI / unit
tests that the committed file is up to date with the CSV data.

Usage:
    python circuit_ESP32C3_Xiao/scripts/generate_vtarget_cal_boards.py
    python circuit_ESP32C3_Xiao/scripts/generate_vtarget_cal_boards.py --check

References: see the ## References section in scripts/README.md.
"""

import argparse
import csv
import glob
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DEFAULT_CSV_DIR = os.path.join(REPO, "tests", "test_results")
DEFAULT_OUT = os.path.join(REPO, "main", "vtarget_cal_boards.c")
DEFAULT_TOL_MV = 6.0
DEFAULT_MAX_POINTS = 32


def load_board_curve(path):
    """Return (board_id, [(duty, mv), ...]) from one measurements CSV."""
    with open(path, newline="") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        raise ValueError(f"{path}: no rows")
    board = rows[0]["board_id"].strip()
    by_duty = {}
    for r in rows:
        by_duty.setdefault(int(r["duty_count"]), []).append(float(r["dmm_mv"]))
    # one value per duty (mean), sorted by duty
    return board, sorted((d, sum(v) / len(v)) for d, v in by_duty.items())


def clean_curve(points):
    """Keep a strictly decreasing voltage sequence (drop noisy points that rise)."""
    out = []
    for duty, mv in points:
        mv = int(round(mv))
        if out and mv >= out[-1][1]:
            continue
        out.append((duty, mv))
    return out


def interp(selected, duty):
    """Forward interpolation voltage(duty) through the selected points."""
    for (d0, v0), (d1, v1) in zip(selected, selected[1:]):
        if d0 <= duty <= d1:
            return v0 - (v0 - v1) * (duty - d0) / (d1 - d0)
    return selected[-1][1]


def reduce_curve(points, tol_mv=DEFAULT_TOL_MV, max_points=DEFAULT_MAX_POINTS):
    """Greedy reduction; returns (selected_points, max_error_mv)."""
    selected = [points[0], points[-1]]
    while True:
        errs = [(abs(interp(selected, d) - v), d, v) for d, v in points]
        worst_err, worst_d, worst_v = max(errs)
        if worst_err <= tol_mv or len(selected) >= max_points:
            return selected, worst_err
        selected.append((worst_d, worst_v))
        selected.sort()


def build_tables(csv_dir=DEFAULT_CSV_DIR, tol_mv=DEFAULT_TOL_MV, max_points=DEFAULT_MAX_POINTS):
    """Return {board_id: (selected_points, max_error_mv, source_file)} sorted by id."""
    tables = {}
    for path in sorted(glob.glob(os.path.join(csv_dir, "vtarget_PCB-*_measurements.csv"))):
        board, raw = load_board_curve(path)
        pts = clean_curve(raw)
        selected, err = reduce_curve(pts, tol_mv, max_points)
        tables[board] = (selected, err, os.path.basename(path))
    return dict(sorted(tables.items()))


def render(tables, tol_mv, max_points):
    lines = []
    w = lines.append
    w("/**")
    w(" * @file vtarget_cal_boards.c")
    w(" * @brief Per-board VTarget calibration tables (GENERATED - do not edit by hand)")
    w(" *")
    w(" * Generated by circuit_ESP32C3_Xiao/scripts/generate_vtarget_cal_boards.py from the")
    w(" * DMM sweeps in tests/test_results/vtarget_PCB-xx_measurements.csv.")
    w(f" * Each curve is reduced to <= {max_points} points within {tol_mv:g} mV of the measured data.")
    w(" * Regenerate after re-measuring a board; `--check` verifies this file is current.")
    w(" *")
    w(" * Note: the sweeps were taken with 0.4 s settling per point (gate filter tau")
    w(" * ~145 ms), so each table carries that settling bias. Re-measure with --settle 1.0")
    w(" * for fully settled tables.")
    w(" */")
    w("")
    w('#include "vtarget_cal.h"')
    w("")
    for board, (pts, err, src) in tables.items():
        ident = board.replace("-", "_")
        w(f"// {board}: {len(pts)} points, range {pts[-1][1]}-{pts[0][1]} mV, "
          f"max fit error {err:.1f} mV ({src})")
        w(f"static const vtarget_cal_point_t {ident}_POINTS[] = {{")
        for i in range(0, len(pts), 5):
            chunk = ", ".join(f"{{ {d}, {v} }}" for d, v in pts[i:i + 5])
            w(f"    {chunk},")
        w("};")
        w("")
    w("const vtarget_cal_table_t VTARGET_CAL_BOARD_TABLES[] = {")
    for board, (pts, _err, _src) in tables.items():
        ident = board.replace("-", "_")
        w(f'    {{ "{board}", {ident}_POINTS, sizeof({ident}_POINTS) / sizeof({ident}_POINTS[0]) }},')
    w("};")
    w("")
    w("const size_t VTARGET_CAL_BOARD_TABLE_COUNT =")
    w("    sizeof(VTARGET_CAL_BOARD_TABLES) / sizeof(VTARGET_CAL_BOARD_TABLES[0]);")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--csv-dir", default=DEFAULT_CSV_DIR)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--tol-mv", type=float, default=DEFAULT_TOL_MV)
    ap.add_argument("--max-points", type=int, default=DEFAULT_MAX_POINTS)
    ap.add_argument("--check", action="store_true", help="exit 1 if --out is not up to date")
    args = ap.parse_args()

    tables = build_tables(args.csv_dir, args.tol_mv, args.max_points)
    if not tables:
        print(f"no measurement CSVs found in {args.csv_dir}", file=sys.stderr)
        return 2
    text = render(tables, args.tol_mv, args.max_points)

    if args.check:
        current = open(args.out, newline="", encoding="utf-8").read().replace("\r\n", "\n") \
            if os.path.exists(args.out) else ""
        if current != text:
            print(f"{args.out} is out of date - run this script without --check", file=sys.stderr)
            return 1
        print(f"{args.out} is up to date ({len(tables)} boards)")
        return 0

    with open(args.out, "w", newline="\n", encoding="utf-8") as f:
        f.write(text)
    for board, (pts, err, _src) in tables.items():
        print(f"{board}: {len(pts):2d} points, {pts[-1][1]}-{pts[0][1]} mV, max error {err:.1f} mV")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
